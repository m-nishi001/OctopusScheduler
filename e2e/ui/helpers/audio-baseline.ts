/** 表の行を ID で引く(spec の名前や理由に使う)。無ければ例外。 */
export function baselineRow(id: string): BaselineRow {
  const row = AUDIO_BASELINE.find((r) => r.id === id);
  if (!row) throw new Error(`audio-baseline: ${id} の行がありません`);
  return row;
}
