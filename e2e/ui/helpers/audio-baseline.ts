/**
 * 音の使用箇所の「正解の動き」(音の再生を1つにまとめる前、main の動き)。
 * 作業ブランチ work/audio-unify では、各 PR で置き換えた行が、この表と同じ動きのままであることを e2e で確かめる。
 * 意図して変える行(`intended`)だけは、変えた理由を添えてこの表を更新する。
 *
 * 列の意味:
 *   plays   : 何が鳴るか(今の仕組み)
 *   loop    : ループするか
 *   stops   : いつ止まるか
 *   fade    : フェードの秒数(フェードなしは「なし」)
 *   delay   : 画面が出てから鳴らすまでの遅れ
 *   venue   : ゲーム中の場内BGM(`AudioControl`)はどうなるか
 *   checkedBy: この動きを機械で確かめている e2e(`e2e/ui/` の spec。名前の `@motion` は動き・音の確認)
 *   pr      : 置き換える PR(計画の「PRの分け方」)
 *   intended: 意図して変える行(理由は `reason`)
 */
